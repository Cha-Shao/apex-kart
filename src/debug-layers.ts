import * as THREE from 'three';
import {LineSegments2} from 'three/addons/lines/LineSegments2.js';
import {LineSegmentsGeometry} from 'three/addons/lines/LineSegmentsGeometry.js';
import {LineMaterial} from 'three/addons/lines/LineMaterial.js';
import type {TrackData} from './track';
import type {TerrainField} from './terrain';
import {runoffScoreTrace} from './runoff-profile';
import {vegetationCoverDensity} from './vegetation-distribution';

export type DebugLayer='bufferPaths'|'grassNoise';

/** Visual inspection of SOURCE algorithm data. The runway-score overlay is
 * not a runoff polygon edge or a collision/physics trajectory: it shows where
 * the squared-speed approach score actually propagates through the circuit,
 * with outward risk/recovery directions generated by the same algorithm. */
export class SceneDebugLayers extends THREE.Group {
  private track:TrackData|null=null;
  private terrain:TerrainField|null=null;
  private readonly buffer=new THREE.Group();
  private readonly density=new THREE.Group();
  private noiseCell='';
  private bufferBuilt=false;
  private pathCounts={scoreSegments:0,highRiskSegments:0,outwardVectors:0};

  constructor(){
    super();this.name='debug-visualization-layers';
    this.buffer.name='debug-runoff-algorithm-score-path';
    this.density.name='debug-grass-density-noise';
    this.buffer.visible=false;this.density.visible=false;
    this.add(this.buffer,this.density);
  }

  private clearLayer(group:THREE.Group){
    group.traverse(object=>{
      if(!(object instanceof THREE.Mesh||object instanceof THREE.LineSegments))return;
      object.geometry.dispose();
      for(const mat of Array.isArray(object.material)?object.material:[object.material])mat.dispose();
    });
    group.clear();
  }

  isVisible(){return this.buffer.visible||this.density.visible;}
  getBufferPathCounts(){return {...this.pathCounts};}

  setTrack(track:TrackData,terrain:TerrainField){
    this.track=track;this.terrain=terrain;this.bufferBuilt=false;this.noiseCell='';
    this.pathCounts={scoreSegments:0,highRiskSegments:0,outwardVectors:0};
    this.clearLayer(this.buffer);this.clearLayer(this.density);
    if(this.buffer.visible)this.buildBuffer();
  }

  setLayer(layer:DebugLayer,visible:boolean){
    const group=layer==='bufferPaths'?this.buffer:this.density;
    group.visible=visible;
    if(visible&&layer==='bufferPaths')this.buildBuffer();
    if(!visible&&layer==='grassNoise'){this.clearLayer(this.density);this.noiseCell='';}
  }

  private addSegments(positions:number[],color:number,name:string,colors?:number[]){
    if(!positions.length)return;
    const geometry=new LineSegmentsGeometry();
    geometry.setPositions(positions);
    if(colors)geometry.setColors(colors);
    const material=new LineMaterial({
      color,linewidth:4,vertexColors:!!colors,
      transparent:true,opacity:.98,depthTest:false,depthWrite:false,toneMapped:false,
    });
    const lines=new LineSegments2(geometry,material);
    lines.name=name;lines.renderOrder=950;lines.frustumCulled=false;
    this.buffer.add(lines);
  }

  private buildBuffer(){
    if(this.bufferBuilt||!this.track||!this.terrain)return;
    this.bufferBuilt=true;
    const trace=runoffScoreTrace(this.track);
    if(!trace||!trace.samples.length)return;
    const {samples}=trace,terrain=this.terrain,n=samples.length;
    const scoreLine:number[]=[],scoreColors:number[]=[],outward:number[]=[];
    const low=new THREE.Color(0x20ddff),high=new THREE.Color(0xff414a);
    const aColor=new THREE.Color(),bColor=new THREE.Color();
    const risk=(i:number)=>{
      const point=samples[i];
      // Risk colour is computed from the SAME lateral demand/severity used by
      // runoff-profile.ts. A top-speed-limited straight is not a danger bend.
      return point.turn?Math.min(1,Math.max(0,point.severity,(point.demand-.45)/.9)):0;
    };
    for(let i=0;i<n;i++){
      const j=(i+1)%n,a=samples[i],b=samples[j],ar=risk(i),br=risk(j);
      scoreLine.push(a.x,terrain.sample(a.x,a.z)+.65,a.z,b.x,terrain.sample(b.x,b.z)+.65,b.z);
      aColor.copy(low).lerp(high,ar);bColor.copy(low).lerp(high,br);
      scoreColors.push(aColor.r,aColor.g,aColor.b,bColor.r,bColor.g,bColor.b);
      if(Math.max(ar,br)>.50)this.pathCounts.highRiskSegments++;

      // Short outward diagnostic vectors originate from scored bends and
      // extend to the score-based recovery budget, before any contour/mesh
      // generation. They are NOT claimed to be simulated vehicle trajectories.
      if(i%Math.max(2,Math.round(n/120))===0&&a.severity>.03&&a.recoveryOffset>.05){
        const previous=samples[(i+n-1)%n],next=samples[(i+1)%n];
        const tx=next.x-previous.x,tz=next.z-previous.z,len=Math.hypot(tx,tz)||1;
        const side=-Math.sign(a.turn),nx=-tz/len*side,nz=tx/len*side;
        const offset=Math.min(24,a.recoveryOffset);
        const x=a.x+nx*offset,z=a.z+nz*offset;
        outward.push(a.x,terrain.sample(a.x,a.z)+.72,a.z,x,terrain.sample(x,z)+.72,z);
        this.pathCounts.outwardVectors++;
      }
    }
    this.pathCounts.scoreSegments=n;
    // One colour-coded computational score path, not a mesh polygon edge.
    this.addSegments(scoreLine,0xffffff,'debug-score-propagation',scoreColors);
    this.addSegments(outward,0xffd24d,'debug-score-recovery-direction');
  }

  update(view:THREE.Vector3){
    if(!this.density.visible||!this.terrain)return;
    const cx=Math.floor(view.x/16),cz=Math.floor(view.z/16),key=`${cx},${cz}`;
    if(key===this.noiseCell)return;
    this.noiseCell=key;this.clearLayer(this.density);
    const step=2,half=60,columns=half*2/step,originX=cx*16-half,originZ=cz*16-half;
    const xyz:number[]=[],colors:number[]=[],indices:number[]=[];
    const sparse=new THREE.Color(0xef7445),dense=new THREE.Color(0x1fd47b),tone=new THREE.Color();
    for(let iz=0;iz<=columns;iz++)for(let ix=0;ix<=columns;ix++){
      const x=originX+ix*step,z=originZ+iz*step,weight=vegetationCoverDensity(x,z);
      xyz.push(x,this.terrain.sample(x,z)+.18,z);
      tone.copy(sparse).lerp(dense,weight);colors.push(tone.r,tone.g,tone.b);
      if(ix<columns&&iz<columns){
        const a=iz*(columns+1)+ix,b=a+columns+1;
        indices.push(a,b,a+1,a+1,b,b+1);
      }
    }
    const geometry=new THREE.BufferGeometry();
    geometry.setAttribute('position',new THREE.Float32BufferAttribute(xyz,3));
    geometry.setAttribute('color',new THREE.Float32BufferAttribute(colors,3));
    geometry.setIndex(indices);geometry.computeBoundingSphere();
    const material=new THREE.MeshBasicMaterial({
      vertexColors:true,transparent:true,opacity:.49,side:THREE.DoubleSide,
      depthTest:true,depthWrite:false,polygonOffset:true,polygonOffsetFactor:-2,
      toneMapped:false,
    });
    const mesh=new THREE.Mesh(geometry,material);
    mesh.name='debug-grass-noise-green-dense-orange-sparse';
    mesh.renderOrder=930;this.density.add(mesh);
  }

  dispose(){
    this.clearLayer(this.buffer);this.clearLayer(this.density);
    this.track=null;this.terrain=null;
  }
}
